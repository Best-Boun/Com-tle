  KEY `idx_payment_audit_refund_time` (`refund_id`,`created_at`),
  KEY `idx_payment_audit_actor_time` (`actor_user_id`,`created_at`),
  CONSTRAINT `fk_payment_audit_payment` FOREIGN KEY (`payment_id`) REFERENCES `payments` (`payment_id`) ON DELETE RESTRICT ON UPDATE RESTRICT,
  CONSTRAINT `fk_payment_audit_refund` FOREIGN KEY (`refund_id`) REFERENCES `refunds` (`refund_id`) ON DELETE RESTRICT ON UPDATE RESTRICT,
  CONSTRAINT `chk_payment_audit_action_not_blank` CHECK ((char_length(trim(`action`)) > 0)),
  CONSTRAINT `chk_payment_audit_exactly_one_target` CHECK ((((`payment_id` is not null) and (`refund_id` is null)) or ((`payment_id` is null) and (`refund_id` is not null))))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

CREATE TABLE `outbox_events` (
  `event_id` char(36) NOT NULL,
  `payment_id` char(36) DEFAULT NULL,
  `refund_id` char(36) DEFAULT NULL,
  `event_type` varchar(100) NOT NULL,
  `payload` json NOT NULL,
  `status` enum('PENDING','PUBLISHED','DEAD_LETTER') NOT NULL DEFAULT 'PENDING',
  `retry_count` int unsigned NOT NULL DEFAULT '0',
  `created_at` datetime(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  `published_at` datetime(3) DEFAULT NULL,
  `next_retry_at` datetime(3) DEFAULT NULL,
  `last_error` text,
  PRIMARY KEY (`event_id`),
  KEY `idx_payment_outbox_retry` (`status`,`next_retry_at`,`created_at`),
  KEY `idx_payment_outbox_payment` (`payment_id`),
  KEY `idx_payment_outbox_refund` (`refund_id`),
  CONSTRAINT `fk_payment_outbox_payment` FOREIGN KEY (`payment_id`) REFERENCES `payments` (`payment_id`) ON DELETE RESTRICT ON UPDATE RESTRICT,
  CONSTRAINT `fk_payment_outbox_refund` FOREIGN KEY (`refund_id`) REFERENCES `refunds` (`refund_id`) ON DELETE RESTRICT ON UPDATE RESTRICT,
  CONSTRAINT `chk_payment_outbox_event_type` CHECK ((char_length(trim(`event_type`)) > 0)),
  CONSTRAINT `chk_payment_outbox_exactly_one_target` CHECK ((((`payment_id` is not null) and (`refund_id` is null)) or ((`payment_id` is null) and (`refund_id` is not null)))),
  CONSTRAINT `chk_payment_outbox_published_time` CHECK (((`status` <> _utf8mb4'PUBLISHED') or (`published_at` is not null)))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

CREATE TABLE `inbox_events` (
  `inbox_id` char(36) NOT NULL,
  `source_service` varchar(50) NOT NULL,
  `source_event_id` char(36) NOT NULL,
  `event_type` varchar(100) NOT NULL,
  `work_order_id` char(36) DEFAULT NULL,
  `payload` json NOT NULL,
  `status` enum('RECEIVED','PROCESSING','PROCESSED','FAILED') NOT NULL DEFAULT 'RECEIVED',
  `received_at` datetime(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  `processed_at` datetime(3) DEFAULT NULL,
  `retry_count` int unsigned NOT NULL DEFAULT '0',
  `last_error` text,
  PRIMARY KEY (`inbox_id`),
  UNIQUE KEY `uq_payment_inbox_source_event` (`source_service`,`source_event_id`),
  KEY `idx_payment_inbox_status_received` (`status`,`received_at`),
  KEY `idx_payment_inbox_work_order` (`work_order_id`),
  CONSTRAINT `chk_payment_inbox_event_type` CHECK ((char_length(trim(`event_type`)) > 0)),
  CONSTRAINT `chk_payment_inbox_processed_time` CHECK (((`status` <> _utf8mb4'PROCESSED') or (`processed_at` is not null))),
  CONSTRAINT `chk_payment_inbox_source_not_blank` CHECK ((char_length(trim(`source_service`)) > 0))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

CREATE TABLE `idempotency_records` (
  `idempotency_id` char(36) NOT NULL,
  `scope_key` varchar(150) NOT NULL,
  `idempotency_key` varchar(100) NOT NULL,
  `operation` varchar(100) NOT NULL,
  `request_hash` char(64) NOT NULL,
  `status` enum('PROCESSING','COMPLETED','FAILED') NOT NULL DEFAULT 'PROCESSING',
  `resource_type` varchar(50) DEFAULT NULL,
  `resource_id` char(36) DEFAULT NULL,
  `response_snapshot` json DEFAULT NULL,
  `created_at` datetime(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  `expires_at` datetime(3) NOT NULL,
  PRIMARY KEY (`idempotency_id`),
  UNIQUE KEY `uq_idempotency_scope_operation_key` (`scope_key`,`operation`,`idempotency_key`),
  KEY `idx_idempotency_expiry` (`expires_at`),
  KEY `idx_idempotency_resource` (`resource_type`,`resource_id`),
  CONSTRAINT `chk_idempotency_completed_response` CHECK (((`status` <> _utf8mb4'COMPLETED') or (`response_snapshot` is not null))),
  CONSTRAINT `chk_idempotency_expiry` CHECK ((`expires_at` > `created_at`)),
  CONSTRAINT `chk_idempotency_hash_format` CHECK (regexp_like(`request_hash`,_utf8mb4'^[0-9a-fA-F]{64}$')),
  CONSTRAINT `chk_idempotency_operation_not_blank` CHECK ((char_length(trim(`operation`)) > 0)),
  CONSTRAINT `chk_idempotency_scope_not_blank` CHECK ((char_length(trim(`scope_key`)) > 0))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

CREATE TABLE `payment_locks` (
