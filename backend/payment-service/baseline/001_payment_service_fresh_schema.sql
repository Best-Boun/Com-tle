CREATE TABLE `payments` (
  `payment_id` char(36) NOT NULL,
  `work_order_id` char(36) NOT NULL,
  `bill_id` char(36) NOT NULL,
  `bill_version` int unsigned NOT NULL,
  `amount` bigint unsigned NOT NULL,
  `currency` char(3) NOT NULL DEFAULT 'THB',
  `payment_method` varchar(30) NOT NULL,
  `status` enum('PENDING','SUCCEEDED','FAILED','VOIDED') NOT NULL DEFAULT 'PENDING',
  `reference_number` varchar(100) DEFAULT NULL,
  `recorded_by` char(36) NOT NULL,
  `voided_by` char(36) DEFAULT NULL,
  `void_reason` varchar(500) DEFAULT NULL,
  `voided_at` datetime(3) DEFAULT NULL,
  `paid_at` datetime(3) DEFAULT NULL,
  `created_at` datetime(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  `updated_at` datetime(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
  PRIMARY KEY (`payment_id`),
  KEY `idx_payments_work_order` (`work_order_id`,`created_at`),
  KEY `idx_payments_bill` (`bill_id`,`bill_version`),
  KEY `idx_payments_status` (`status`),
  KEY `idx_payments_recorded_by` (`recorded_by`),
  CONSTRAINT `chk_payments_amount_positive` CHECK ((`amount` > 0)),
  CONSTRAINT `chk_payments_bill_version_positive` CHECK ((`bill_version` > 0)),
  CONSTRAINT `chk_payments_currency_format` CHECK (regexp_like(`currency`,_utf8mb4'^[A-Z]{3}$')),
  CONSTRAINT `chk_payments_method_not_blank` CHECK ((char_length(trim(`payment_method`)) > 0)),
  CONSTRAINT `chk_payments_paid_timestamp` CHECK (((`status` <> _utf8mb4'SUCCEEDED') or (`paid_at` is not null))),
  CONSTRAINT `chk_payments_void_fields` CHECK ((((`status` = _utf8mb4'VOIDED') and (`voided_by` is not null) and (`void_reason` is not null) and (char_length(trim(`void_reason`)) > 0) and (`voided_at` is not null)) or ((`status` <> _utf8mb4'VOIDED') and (`voided_by` is null) and (`void_reason` is null) and (`voided_at` is null))))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

CREATE TABLE `refunds` (
  `refund_id` char(36) NOT NULL,
  `payment_id` char(36) NOT NULL,
  `work_order_id` char(36) NOT NULL,
  `amount` bigint unsigned NOT NULL,
  `currency` char(3) NOT NULL DEFAULT 'THB',
  `status` enum('REQUESTED','APPROVED','REJECTED','PROCESSING','COMPLETED','FAILED') NOT NULL DEFAULT 'REQUESTED',
  `requested_by` char(36) NOT NULL,
  `approved_by` char(36) DEFAULT NULL,
  `reason` varchar(500) NOT NULL,
  `rejection_reason` varchar(500) DEFAULT NULL,
  `requested_at` datetime(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  `approved_at` datetime(3) DEFAULT NULL,
  `processed_at` datetime(3) DEFAULT NULL,
  `completed_at` datetime(3) DEFAULT NULL,
  `rejected_at` datetime(3) DEFAULT NULL,
  `failed_at` datetime(3) DEFAULT NULL,
  `created_at` datetime(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  `updated_at` datetime(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
  PRIMARY KEY (`refund_id`),
  KEY `idx_refunds_payment_status` (`payment_id`,`status`),
  KEY `idx_refunds_work_order` (`work_order_id`),
  KEY `idx_refunds_requester_time` (`requested_by`,`requested_at`),
  KEY `idx_refunds_status_time` (`status`,`requested_at`),
  CONSTRAINT `fk_refunds_payment` FOREIGN KEY (`payment_id`) REFERENCES `payments` (`payment_id`) ON DELETE RESTRICT ON UPDATE RESTRICT,
  CONSTRAINT `chk_refunds_amount_positive` CHECK ((`amount` > 0)),
  CONSTRAINT `chk_refunds_approval_fields` CHECK (((`status` not in (_utf8mb4'APPROVED',_utf8mb4'PROCESSING',_utf8mb4'COMPLETED')) or ((`approved_by` is not null) and (`approved_at` is not null)))),
  CONSTRAINT `chk_refunds_approver_not_requester` CHECK (((`approved_by` is null) or (`approved_by` <> `requested_by`))),
  CONSTRAINT `chk_refunds_completion_timestamp` CHECK (((`status` <> _utf8mb4'COMPLETED') or (`completed_at` is not null))),
  CONSTRAINT `chk_refunds_currency_format` CHECK (regexp_like(`currency`,_utf8mb4'^[A-Z]{3}$')),
  CONSTRAINT `chk_refunds_failure_timestamp` CHECK (((`status` <> _utf8mb4'FAILED') or (`failed_at` is not null))),
  CONSTRAINT `chk_refunds_reason_not_blank` CHECK ((char_length(trim(`reason`)) > 0)),
  CONSTRAINT `chk_refunds_rejection_fields` CHECK (((`status` <> _utf8mb4'REJECTED') or ((`rejected_at` is not null) and (`rejection_reason` is not null) and (char_length(trim(`rejection_reason`)) > 0))))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

