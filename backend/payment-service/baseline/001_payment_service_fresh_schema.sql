  `is_locked` tinyint(1) NOT NULL DEFAULT '0',
  `lock_reason` varchar(255) DEFAULT NULL,
  `source_event_id` char(36) DEFAULT NULL,
  `locked_at` datetime(3) DEFAULT NULL,
  `updated_at` datetime(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
  PRIMARY KEY (`lock_id`),
  UNIQUE KEY `uq_payment_locks_work_order` (`work_order_id`),
  KEY `idx_payment_locks_is_locked` (`is_locked`),
  CONSTRAINT `chk_payment_locks_reason` CHECK (((`is_locked` = false) or ((`lock_reason` is not null) and (char_length(trim(`lock_reason`)) > 0)))),
  CONSTRAINT `chk_payment_locks_timestamp` CHECK (((`is_locked` = false) or (`locked_at` is not null)))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;
